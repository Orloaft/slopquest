import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { PNG } from "pngjs";

type Dir = "up" | "right" | "down" | "left";
type DrawColor = keyof typeof COLORS;

const repoRoot = process.cwd();
const sourceDir = path.join(repoRoot, "assetsources/gbc/actors");
const publicDir = path.join(repoRoot, "public/sprites/actors");
const artifactDir = path.join(repoRoot, "artifacts/art-new-direction/player-actor-gen2-quality");
