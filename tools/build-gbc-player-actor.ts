mkdirSync(publicDir, { recursive: true });
mkdirSync(artifactDir, { recursive: true });

const baselineSource = readGitBaselinePng("assetsources/gbc/actors/player-source.png");
const source = new PNG({ width: frameW * 4, height: frameH * 4 });
source.data.fill(0);

for (let row = 0; row < dirs.length; row += 1) {
  for (let frame = 0; frame < 4; frame += 1) {
    drawFrame(source, frame * frameW, row * frameH, {
      dir: dirs[row] ?? "down",
      frame,
      step: ([-1, 0, 1, 0][frame] ?? 0) as -1 | 0 | 1
    });
  }
}

const runtime = nearestScale(source, runtimeScale);
writePng(path.join(sourceDir, "player-source.png"), source);
writePng(path.join(sourceDir, "player-runtime.png"), runtime);
writePng(path.join(publicDir, "player-gbc-runtime.png"), runtime);

if (baselineSource) writePng(path.join(artifactDir, "player-old-vs-new-source-comparison.png"), oldVsNewSourceComparison(baselineSource, source));
writePng(path.join(artifactDir, "player-source-contact-sheet.png"), contactSheet(source, frameW, frameH, 3));
writePng(path.join(artifactDir, "player-runtime-contact-sheet.png"), contactSheet(runtime, frameW * runtimeScale, frameH * runtimeScale, 2));
writePng(path.join(artifactDir, "player-grayscale-readability-contact-sheet.png"), grayscaleContact(runtime));

